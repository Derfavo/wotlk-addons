local clientLocale = GetLocale()
local localeTranslations = {
    deDE = german,
    enUS = english,
    enGB = english,
}
local translations = localeTranslations[clientLocale] or english

addon.localeCode = clientLocale

function addon.locale(key, ...)
    local value = translations[key] or english[key] or key

    if select("#", ...) > 0 then
        return string.format(value, ...)
    end

    return value
end
